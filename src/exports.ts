import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import type { InspectionReport } from "./types.js";

// F8: One-Click PE Sign-Off Permit Packet (printable stamped PDF)
export async function permitPacketPdf(report: InspectionReport): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const page = doc.addPage([612, 792]);
  let y = 740;

  const line = (text: string, size = 11, useBold = false) => {
    page.drawText(text.slice(0, 110), {
      x: 48,
      y,
      size,
      font: useBold ? bold : font,
      color: rgb(0.08, 0.1, 0.14),
    });
    y -= size + 8;
  };

  line("PlanPass — Permit Compliance Packet", 16, true);
  line(`Inspection: ${report.inspectionId}`);
  line(`Occupancy: ${report.occupancy}  |  Source plan: ${report.planId ?? "upload"}`);
  line(`Permit Readiness Score: ${report.readinessScore}/100`);
  line(`Status: ${report.status === "APPROVED" ? "APPROVED FOR PE SIGN-OFF" : "HOLD — REVISIONS REQUIRED"}`, 12, true);
  y -= 8;
  line("Statutory Checklist", 13, true);
  if (!report.violations.length) line("No outstanding violations. All sampled IBC/ADA/IRC checks pass.");
  for (const v of report.violations) {
    line(`${v.id} [${v.severity}] ${v.title}`, 11, true);
    line(`  Code: ${v.codeSection}`);
    line(`  Measured: ${v.measuredValue}`);
    line(`  Required: ${v.requiredValue}`);
  }
  y -= 8;
  line("Agent & MCP Execution Trace", 13, true);
  for (const t of report.trace) line(`Node ${t.node} ${t.model}: ${t.status} (${t.latencyMs} ms)`);
  for (const m of report.mcpTrace) line(`MCP ${m.tool}: ${m.output.slice(0, 90)}...`);
  for (const w of report.warnings ?? []) line(`Warning: ${w}`);
  y -= 12;
  line(report.status === "APPROVED" ? "PE STAMP: APPROVED FOR SIGN-OFF" : "PE STAMP: WITHHELD — HOLD", 13, true);
  line("Generated by PlanPass AI Municipal Blueprint & Code Compliance Examiner.");

  return doc.save();
}

// F9: Sovereign dataset flywheel export (JSONL)
export function datasetJsonl(report: InspectionReport): string {
  return (
    JSON.stringify({
      inspection_id: report.inspectionId,
      readiness_score: report.readinessScore,
      status: report.status,
      transcript: report.transcript,
      sam_overlays: report.samOverlays,
      violations: report.violations,
      mcp_trace: report.mcpTrace,
      warnings: report.warnings ?? [],
    }) + "\n"
  );
}

export function csvEscape(v: string): string {
  return `"${v.replace(/"/g, '""')}"`;
}
